"""Design-time generation of dbt models and tests from data contracts.

A contract (``configs/contracts/<source>/<dataset>.yml`` or a draft in a dossier) says what a
dataset delivers: typed columns, which are required, the primary key and the privacy class of each
column. From it this module generates, deterministically and without any LLM (invariant 1):

* ``sources/_src_<source>.yml``: the typed ``bronze.<source>__<dataset>`` tables the runtime loads;
* ``staging/<source>/stg_<source>__<dataset>.sql``: typed, row-preserving view of that table;
* ``intermediate/<source>/int_<source>__<dataset>.sql``: current version of each record;
* the schema YAML with descriptions, ``pii`` tags and the tests the contract implies
  (``not_null`` for required and key columns, ``unique`` for the key of the current model);
* singular SQL tests where a uniqueness rule spans several columns.

Only argument-free tests are generated, so the output is valid for every dbt version (the
``arguments:`` property of generic tests is not understood by dbt 1.8 and required by newer ones).
Convention: a column is read from the payload key of the same name; sources whose payload keys
differ need a hand-designed staging model (a design decision, not something to guess).
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import jinja2
import yaml

from scrapagents.contracts.loader import load_contract, load_yaml
from scrapagents.contracts.validator import validate_contract
from scrapagents.paths import REPO_ROOT

DBT_DIR = REPO_ROOT / "dbt"
HEADER = "Generated by `scrapagents generate-dbt`"
# Lineage columns every staging model carries, taken from the bronze table's `_...` columns.
BRONZE_COLUMNS = (
    "bronze_batch_id",
    "bronze_record_hash",
    "bronze_landing_uri",
    "bronze_ingested_at",
)
PII_CLASSES = frozenset({"personal", "sensitive"})

SQL_TYPES = {
    "string": "text",
    "integer": "bigint",
    "number": "numeric",
    "boolean": "boolean",
    "date": "date",
    "timestamp": "timestamptz",
}
JSON_TYPES = frozenset({"object", "array", "json"})
_IDENT = re.compile(r"^[a-z_][a-z0-9_]*$")
# Columns may keep the source's spelling (a source may spell a column `COLA_Codigo`): Postgres folds
# unquoted identifiers to lower case, so anything but plain lower case is emitted quoted.
_COLUMN = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def ident(name: str) -> str:
    return name if _IDENT.match(name) else f'"{name}"'


class DbtGenerationError(ValueError):
    pass


def _sq(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


_ENV = jinja2.Environment(
    loader=jinja2.PackageLoader("scrapagents.dbt", "templates"),
    undefined=jinja2.StrictUndefined,
    trim_blocks=True,
    keep_trailing_newline=True,
    autoescape=False,
)
_ENV.filters["j"] = lambda v: json.dumps(v, ensure_ascii=False)
_ENV.filters["sq"] = _sq


@dataclass(frozen=True)
class Contract:
    data: dict[str, Any]
    ref: str  # stable text for the generated headers

    @property
    def source(self) -> str:
        return self.data["source_system"]

    @property
    def dataset(self) -> str:
        return self.data["dataset"]


def _cell(text: str) -> str:
    return " ".join(str(text).split())


def validate_for_dbt(contract: Contract) -> None:
    errors = validate_contract(contract.data)
    if errors:
        raise DbtGenerationError(f"{contract.ref}: " + "; ".join(errors))
    for name in (contract.source, contract.dataset):
        if not _IDENT.match(name):
            raise DbtGenerationError(f"{contract.ref}: {name!r} is not a valid identifier")
    names = []
    for col in contract.data["columns"]:
        if not _COLUMN.match(col["name"]):
            raise DbtGenerationError(f"{contract.ref}: column {col['name']!r} is not valid")
        if col["name"] in BRONZE_COLUMNS:
            raise DbtGenerationError(f"{contract.ref}: column {col['name']!r} is reserved")
        names.append(col["name"])
    if len(set(names)) != len(names):
        raise DbtGenerationError(f"{contract.ref}: duplicate column names")
    for key in contract.data["primary_key"]:
        if key not in names:
            raise DbtGenerationError(f"{contract.ref}: primary key column {key!r} is not declared")


def _expr(col: dict[str, Any]) -> str:
    key = _sq(col["name"])
    if col["name"] == "payload" and col["type"] in JSON_TYPES:
        return "record"
    if col["type"] in JSON_TYPES:
        return f"record -> {key}"
    return f"(record ->> {key})::{SQL_TYPES[col['type']]}"


def _column_yaml(col: dict[str, Any], key_columns: set[str]) -> dict[str, Any]:
    out: dict[str, Any] = {"name": col["name"], "description": _cell(col["description"])}
    if not _IDENT.match(col["name"]):
        out["quote"] = True
    classification = col.get("classification")
    if classification:
        out["meta"] = {"classification": classification}
        if col.get("purpose"):
            out["meta"]["purpose"] = _cell(col["purpose"])
        if classification in PII_CLASSES:
            out["tags"] = ["pii"]
    if col.get("required") or col["name"] in key_columns:
        out["data_tests"] = ["not_null"]
    return out


_BRONZE_DOCS = (
    ("bronze_batch_id", "Batch (landed payload) this record came from; same bytes, same batch."),
    ("bronze_record_hash", "SHA-256 of the record as landed, to detect changes between batches."),
    ("bronze_landing_uri", "Landing object the record was read from (provenance)."),
    ("bronze_ingested_at", "When the RustWorker loaded that payload into bronze."),
)


def _model_yaml(
    name: str, description: str, contract: Contract, unique_column: str | None, layer: str
) -> dict[str, Any]:
    d = contract.data
    keys = set(d["primary_key"])
    columns = []
    for col in d["columns"]:
        entry = _column_yaml(col, keys)
        if unique_column == col["name"]:
            entry["data_tests"] = [*entry.get("data_tests", []), "unique"]
        columns.append(entry)
    for bronze_name, text in _BRONZE_DOCS:
        columns.append({"name": bronze_name, "description": text, "data_tests": ["not_null"]})
    return {
        "name": name,
        "description": description,
        "meta": {
            "layer": layer,
            "owner": d["owner"],
            "source_system": contract.source,
            "dataset": contract.dataset,
            "grain": _cell(d["grain"]),
            "generated": True,
        },
        "columns": columns,
    }


def _sources_yaml(source: str, group: list[Contract], refs: list[str]) -> str:
    tables = []
    for contract in group:
        d = contract.data
        keys = []
        for key in d["primary_key"]:
            entry: dict[str, Any] = {"name": key, "data_tests": ["not_null"]}
            if not _IDENT.match(key):
                entry["quote"] = True
            keys.append(entry)
        lineage = [
            {"name": name, "data_tests": ["not_null"]}
            for name in ("payload", "_batch_id", "_landing_uri", "_record_hash", "_ingested_at")
        ]
        tables.append(
            {
                "name": contract.dataset,
                "identifier": f"{source}__{contract.dataset}",
                "description": f"{_cell(d['description'])} One row per record per batch "
                f"(key: {', '.join(d['primary_key'])} + _batch_id).",
                "columns": [*keys, *lineage],
            }
        )
    doc = {
        "version": 2,
        "sources": [
            {
                "name": source,
                "schema": "bronze",
                "description": f"Typed bronze tables of {source}, loaded by the RustWorker.",
                "tables": tables,
            }
        ],
    }
    head = (
        f"# {HEADER} from {', '.join(refs)}.\n"
        "# Do not edit: change the contract and regenerate.\n"
    )
    return head + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=100)


def _yaml_file(models: list[dict[str, Any]], refs: list[str]) -> str:
    head = (
        f"# {HEADER} from {', '.join(refs)}.\n"
        "# Do not edit: change the contract and regenerate.\n"
    )
    body = yaml.safe_dump(
        {"version": 2, "models": models}, sort_keys=False, allow_unicode=True, width=100
    )
    return head + body


def build_files(contracts: list[Contract]) -> dict[str, str]:
    """Relative path (under ``dbt/``) -> content, for every generated file."""
    files: dict[str, str] = {}
    by_source: dict[str, list[Contract]] = {}
    for contract in contracts:
        validate_for_dbt(contract)
        by_source.setdefault(contract.source, []).append(contract)

    for source, group in by_source.items():
        stg_models: list[dict[str, Any]] = []
        int_models: list[dict[str, Any]] = []
        for contract in group:
            d = contract.data
            ds, pk = contract.dataset, list(d["primary_key"])
            stg, cur = f"stg_{source}__{ds}", f"int_{source}__{ds}"
            tag = f"source_{source}"
            common = {"contract_ref": contract.ref, "tag": tag}
            files[f"models/staging/{source}/{stg}.sql"] = _ENV.get_template("stg.sql.j2").render(
                **common,
                source_system=source,
                dataset=ds,
                columns=[{"name": ident(c["name"]), "expr": _expr(c)} for c in d["columns"]],
            )
            files[f"models/intermediate/{source}/{cur}.sql"] = _ENV.get_template(
                "int.sql.j2"
            ).render(**common, stg_model=stg, pk=[ident(k) for k in pk])

            stg_models.append(
                _model_yaml(
                    stg,
                    f"{_cell(d['description'])} Typed and row-preserving: one row per record "
                    "per landed payload.",
                    contract,
                    None,
                    "staging",
                )
            )
            int_models.append(
                _model_yaml(
                    cur,
                    f"{_cell(d['description'])} Current version: latest ingested row per "
                    f"primary key ({', '.join(pk)}).",
                    contract,
                    pk[0] if len(pk) == 1 else None,
                    "intermediate",
                )
            )
            # A record must appear once per batch; a repeat inside one batch is a defect.
            files[f"tests/generated/{source}/{stg}__grain.sql"] = _ENV.get_template(
                "grain_test.sql.j2"
            ).render(
                contract_ref=contract.ref,
                message=f"Grain of {stg}: ({', '.join([*pk, 'bronze_batch_id'])}) is unique.",
                keys=[*(ident(k) for k in pk), "bronze_batch_id"],
                model=stg,
            )
            if len(pk) > 1:
                files[f"tests/generated/{source}/{cur}__pk.sql"] = _ENV.get_template(
                    "grain_test.sql.j2"
                ).render(
                    contract_ref=contract.ref,
                    message=f"Primary key of {cur}: ({', '.join(pk)}) is unique.",
                    keys=[ident(k) for k in pk],
                    model=cur,
                )
        refs = [c.ref for c in group]
        files[f"models/sources/_src_{source}.yml"] = _sources_yaml(source, group, refs)
        files[f"models/staging/{source}/_stg_{source}.yml"] = _yaml_file(stg_models, refs)
        files[f"models/intermediate/{source}/_int_{source}.yml"] = _yaml_file(int_models, refs)
    return files


def _display(path: Path) -> str:
    try:
        return path.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return path.name


def contract_from_file(path: Path) -> Contract:
    data = load_yaml(path)
    if not isinstance(data, dict):
        raise DbtGenerationError(f"{path}: contract must be a mapping")
    return Contract(data, _display(path))


def contract_from_catalog(source_system: str, dataset: str) -> Contract:
    ref = f"configs/contracts/{source_system}/{dataset}.yml"
    return Contract(load_contract(source_system, dataset), ref)


def load_contracts(
    files: list[Path], catalog: list[tuple[str, str]]
) -> tuple[list[Contract], list[str]]:
    contracts: list[Contract] = []
    errors: list[str] = []
    for path in files:
        try:
            contracts.append(contract_from_file(path))
        except (DbtGenerationError, OSError, ValueError) as exc:
            errors.append(f"{path}: {exc}")
    for source, dataset in catalog:
        try:
            contracts.append(contract_from_catalog(source, dataset))
        except (DbtGenerationError, FileNotFoundError, ValueError) as exc:
            errors.append(f"{source}/{dataset}: {exc}")
    return contracts, errors


def generate(
    files: list[Path], catalog: list[tuple[str, str]]
) -> tuple[dict[str, str], list[str]]:
    contracts, errors = load_contracts(files, catalog)
    if errors:
        return {}, errors
    try:
        return build_files(contracts), []
    except DbtGenerationError as exc:
        return {}, [str(exc)]


def write_files(files: dict[str, str], dbt_dir: Path) -> None:
    for rel, content in files.items():
        target = dbt_dir / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")


def _generated_on_disk(dbt_dir: Path) -> set[str]:
    found: set[str] = set()
    for sub in ("models/sources", "models/staging", "models/intermediate", "tests/generated"):
        for path in (dbt_dir / sub).rglob("*") if (dbt_dir / sub).is_dir() else []:
            if path.suffix in {".sql", ".yml"} and HEADER in path.read_text(encoding="utf-8"):
                found.add(path.relative_to(dbt_dir).as_posix())
    return found


def check_files(files: dict[str, str], dbt_dir: Path) -> list[str]:
    """Differences between the generated output and the files committed under ``dbt_dir``."""
    problems = []
    for rel, content in files.items():
        path = dbt_dir / rel
        if not path.is_file():
            problems.append(f"{path}: missing (run `make generate-dbt`)")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"{path}: out of date with its contract (run `make generate-dbt`)")
    for rel in sorted(_generated_on_disk(dbt_dir) - set(files)):
        problems.append(f"{dbt_dir / rel}: no contract generates it")
    return problems
