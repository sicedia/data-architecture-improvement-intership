"""Design-time generation of the typed bronze layer from data contracts (no LLM, invariant 1).

Every dataset is loaded into its own table, ``bronze.<source_system>__<dataset>``, with the key
columns, the record as ``payload`` (JSONB) and lineage columns (``_ingested_at``, ``_batch_id``,
``_landing_uri``, ``_record_hash``). This module generates, from the contracts:

* ``bronze/tables.sql``: idempotent DDL for those tables (applied by ``make bronze-apply``);
* ``bronze/registry.json``: which datasets have a table and which columns form the key, read by the
  RustWorker at start-up. The runtime never derives a table name or a key from a payload.

The key is the contract's ``primary_key``. Key columns are TEXT; staging models cast
them to the contract's types.
"""

from __future__ import annotations

import json
from pathlib import Path

from scrapagents.dbt.generator import (
    Contract,
    DbtGenerationError,
    ident,
    load_contracts,
    validate_for_dbt,
)
from scrapagents.paths import REPO_ROOT

BRONZE_DIR = REPO_ROOT / "bronze"
HEADER = "Generated by `scrapagents generate-bronze`"
LINEAGE_COLUMNS = ("payload", "_ingested_at", "_batch_id", "_landing_uri", "_record_hash")
# `ix_<table>_batch` must fit PostgreSQL's 63 bytes; the runtime enforces the same limit.
MAX_TABLE_LENGTH = 54


class BronzeGenerationError(ValueError):
    pass


def table_name(contract: Contract) -> str:
    return f"{contract.source}__{contract.dataset}"


def _validate(contract: Contract) -> None:
    try:
        validate_for_dbt(contract)
    except DbtGenerationError as exc:
        raise BronzeGenerationError(str(exc)) from exc
    table = table_name(contract)
    if len(table) > MAX_TABLE_LENGTH:
        raise BronzeGenerationError(
            f"{contract.ref}: table name {table!r} is longer than {MAX_TABLE_LENGTH} characters"
        )
    for key in contract.data["primary_key"]:
        if key in LINEAGE_COLUMNS:
            raise BronzeGenerationError(f"{contract.ref}: key column {key!r} is reserved")


def _ddl(contract: Contract) -> str:
    table, keys = table_name(contract), list(contract.data["primary_key"])
    columns = [f"    {ident(key)} TEXT NOT NULL," for key in keys]
    primary_key = ", ".join([*(ident(k) for k in keys), "_batch_id"])
    return "\n".join(
        [
            f"-- {contract.source}/{contract.dataset} ({contract.ref}); key: {', '.join(keys)}",
            f"CREATE TABLE IF NOT EXISTS bronze.{table} (",
            *columns,
            "    payload JSONB NOT NULL,",
            "    _ingested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),",
            "    _batch_id UUID NOT NULL,",
            "    _landing_uri TEXT NOT NULL,",
            "    _record_hash TEXT NOT NULL,",
            f"    PRIMARY KEY ({primary_key})",
            ");",
            f"CREATE INDEX IF NOT EXISTS ix_{table}_batch ON bronze.{table} (_batch_id);",
        ]
    )


def build_files(contracts: list[Contract]) -> dict[str, str]:
    """Relative path (under ``bronze/``) -> content."""
    ordered = sorted(contracts, key=lambda c: (c.source, c.dataset))
    tables: dict[str, Contract] = {}
    for contract in ordered:
        _validate(contract)
        table = table_name(contract)
        if table in tables:
            raise BronzeGenerationError(f"{contract.ref}: table {table!r} is declared twice")
        tables[table] = contract

    sql = [
        f"-- {HEADER}. Do not edit: change the contracts and regenerate.",
        "-- Idempotent; apply with `make bronze-apply`.",
        "-- Generated from configs/contracts; do not edit by hand.",
        "CREATE SCHEMA IF NOT EXISTS bronze;",
        "",
        "\n\n".join(_ddl(c) for c in ordered),
        "",
    ]
    registry = {
        "generated_by": HEADER,
        "datasets": {
            f"{c.source}/{c.dataset}": {
                "table": table_name(c),
                "keys": list(c.data["primary_key"]),
            }
            for c in ordered
        },
    }
    return {
        "tables.sql": "\n".join(sql),
        "registry.json": json.dumps(registry, indent=2, sort_keys=True) + "\n",
    }


def generate(
    files: list[Path], catalog: list[tuple[str, str]]
) -> tuple[dict[str, str], list[str]]:
    contracts, errors = load_contracts(files, catalog)
    if errors:
        return {}, errors
    try:
        return build_files(contracts), []
    except BronzeGenerationError as exc:
        return {}, [str(exc)]


def write_files(files: dict[str, str], out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for rel, content in files.items():
        (out_dir / rel).write_text(content, encoding="utf-8", newline="\n")


def check_files(files: dict[str, str], out_dir: Path) -> list[str]:
    problems = []
    for rel, content in files.items():
        path = out_dir / rel
        if not path.is_file():
            problems.append(f"{path}: missing (run `make generate-bronze`)")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"{path}: out of date with its contracts (run `make generate-bronze`)")
    return problems
